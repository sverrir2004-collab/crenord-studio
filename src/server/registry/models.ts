/**
 * Derives inputKind ('text' | 'image' | 'both' | 'video' | 'audio') from endpoint and tool
 */
export function deriveInputKind(endpoint: string, tool?: string): 'text' | 'image' | 'both' | 'video' | 'audio' {
  const ep = (endpoint || '').toLowerCase();
  if (tool?.startsWith('audio.') || ep.includes('elevenlabs') || ep.includes('whisper') || ep.includes('audio') || ep.includes('f5-tts')) {
    return 'audio';
  }
  if (ep.includes('video-to-video') || ep.includes('delogo') || ep.includes('video_eraser') || ep.includes('video-upscaler') || ep.includes('burn-captions')) {
    return 'video';
  }
  const isImage = ep.includes('image-to-video') || ep.includes('image-to-image') || ep.includes('/edit') || ep.includes('upscale') || ep.includes('inpaint');
  const isText = ep.includes('text-to-video') || ep.includes('text-to-image');
  if (isImage && isText) return 'both';
  if (isImage) return 'image';
  if (isText) return 'text';
  if (tool === 'image.create') return 'text';
  if (tool === 'video.create') return 'text';
  return 'text';
}

